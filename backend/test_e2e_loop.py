"""
VeriForm — Complete End-to-End Loop Test
Executes:
  1. Upload Form-B image
  2. Verify doubts generated by validation engine
  3. Resolve doubts in Review Queue
  4. Finalize form
  5. View Room-wise and Branch-wise Summaries
  6. Ask Chatbot queries
"""

import asyncio
from pathlib import Path
from uuid import UUID, uuid4
from httpx import AsyncClient, ASGITransport

from app.main import app
from app.db.auth import require_user

IMG_PATH = Path(r"C:\Users\Bhanu Prasad\.gemini\antigravity\brain\2a7b1fdb-115e-4f25-b590-6870b1c31242\.user_uploaded\media_1795764705639_ccef725c.jpg")
TEST_USER = UUID("0f10cfde-61c9-47f0-8659-58f2ec7dedb3")

async def run_e2e():
    app.dependency_overrides[require_user] = lambda: TEST_USER
    
    async with AsyncClient(transport=ASGITransport(app=app), base_url="http://test", timeout=120.0) as client:
        print("=" * 60)
        print("STEP 1: UPLOAD FORM-B")
        print("=" * 60)
        img_bytes = IMG_PATH.read_bytes()
        files = {"file": ("CDS_105_FormB.jpg", img_bytes, "image/jpeg")}
        
        resp = await client.post("/api/forms/upload", files=files)
        if resp.status_code != 201:
            print(f"FAILED upload: {resp.status_code} -> {resp.text}")
            return
        
        form_data = resp.json()
        form_id = form_data["id"]
        print(f"-> Form created: ID={form_id}")
        print(f"   Room: {form_data['room_no']}, Exam: {form_data['exam_name']}")
        print(f"   Status: {form_data['status']}")
        print(f"   Sessions: {len(form_data.get('sessions', []))}")
        print(f"   Attendance rows: {len(form_data.get('attendance', []))}")
        print(f"   Initial Doubts: {len(form_data.get('doubts', []))}")
        print(f"   Image URL preview: {form_data.get('image_url')[:60] if form_data.get('image_url') else 'None'}...")

        print("\n" + "=" * 60)
        print("STEP 2: DOUBTS GENERATED IN REVIEW QUEUE")
        print("=" * 60)
        resp = await client.get(f"/api/forms/{form_id}/doubts?resolved=false")
        assert resp.status_code == 200
        doubts = resp.json()
        print(f"-> Found {len(doubts)} open doubt(s) requiring human confirmation:")
        for i, d in enumerate(doubts, 1):
            print(f"   {i}. [{d['type']}] {d['message']} (AI Guess: {d.get('ai_guess')})")

        print("\n" + "=" * 60)
        print("STEP 3: RESOLVE IN REVIEW QUEUE")
        print("=" * 60)
        # Try to finalize before resolving to verify blocking
        early_finalize = await client.post(f"/api/forms/{form_id}/finalize")
        print(f"-> Attempting to finalize with open doubts: Status {early_finalize.status_code} ({early_finalize.json().get('detail')})")
        assert early_finalize.status_code == 409, "Finalize must be blocked while doubts are open!"
        
        # Human resolution for each doubt
        for d in doubts:
            if d.get("attendance_id"):
                resolution = d.get("ai_guess") or "present"
                if resolution == "unclear":
                    resolution = "present"
                att_status = resolution
            else:
                resolution = "Verified footer count with room invigilator"
                att_status = None
            
            res_payload = {
                "resolution": resolution,
                "resolved_by": str(TEST_USER),
                "attendance_status": att_status
            }
            res_resp = await client.post(f"/api/doubts/{d['id']}/resolve", json=res_payload)
            assert res_resp.status_code == 200, f"Failed resolving doubt {d['id']}: {res_resp.text}"
            print(f"   Resolved [{d['type']}] -> '{resolution}'")

        # Verify no open doubts remain
        check_doubts = await client.get(f"/api/forms/{form_id}/doubts?resolved=false")
        remaining = len(check_doubts.json())
        print(f"-> Remaining open doubts: {remaining}")
        assert remaining == 0

        print("\n" + "=" * 60)
        print("STEP 4: FINALIZE FORM")
        print("=" * 60)
        fin_resp = await client.post(f"/api/forms/{form_id}/finalize")
        assert fin_resp.status_code == 200, f"Finalize failed: {fin_resp.text}"
        final_form = fin_resp.json()
        print(f"-> Form {form_id} finalized successfully! Status: {final_form['status']}")

        print("\n" + "=" * 60)
        print("STEP 5: VIEW SUMMARY (ROOM & BRANCH)")
        print("=" * 60)
        # Room summary
        room_resp = await client.get("/api/summary/room/CDS 105")
        assert room_resp.status_code == 200
        room_summary = room_resp.json()
        print(f"-> Room Summary for {room_summary['room_no']}:")
        for sess in room_summary["sessions"]:
            print(f"   • {sess['exam_date']} ({sess['subject_code']}): Total={sess['total']}, Present={sess['present']}, Absent={sess['absent']}, Verified={sess.get('verified')} ({sess['percentage']}%)")
            if sess['absent_students']:
                abs_names = [f"{st['usn']} ({st['name']})" for st in sess['absent_students']]
                print(f"     Absentees: {', '.join(abs_names)}")

        # Branch summary
        branch_resp = await client.get("/api/summary/branch/CY")
        assert branch_resp.status_code == 200
        branch_summary = branch_resp.json()
        print(f"\n-> Branch Summary for '{branch_summary['branch']}':")
        for sess in branch_summary["sessions"]:
            print(f"   • {sess['exam_date']} ({sess['subject_code']}): Total={sess['total']}, Present={sess['present']}, Absent={sess['absent']} ({sess['percentage']}%)")

        print("\n" + "=" * 60)
        print("STEP 6: ASK CHATBOT")
        print("=" * 60)
        questions = [
            "Who was absent in Room CDS 105 on 03-11-2026?",
            "What is the attendance summary for Cyber Security branch (CY)?",
            "Who was absent in more than one paper?"
        ]
        for q in questions:
            print(f"\nUser: {q}")
            chat_resp = await client.post("/api/chat", json={"user_id": str(TEST_USER), "message": q})
            assert chat_resp.status_code == 200
            replies = chat_resp.json()
            if replies:
                print(f"VeriForm AI: {replies[0]['content']}")

        print("\n" + "=" * 60)
        print("🎉 FULL END-TO-END LOOP COMPLETED SUCCESSFULLY!")
        print("=" * 60)

if __name__ == "__main__":
    asyncio.run(run_e2e())
